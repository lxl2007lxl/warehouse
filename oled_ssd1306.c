// I2C发送命令
static void OLED_Write_Cmd(uint8_t cmd)
{
    hi_i2c_data i2c_buf = {0};
    uint8_t buf[2];
    buf[0] = 0x00;
    buf[1] = cmd;
    i2c_buf.send_buf = buf;
    i2c_buf.send_len = 2;
    hi_i2c_write(0, OLED_ADDR, &i2c_buf);
}

// I2C发送数据
static void OLED_Write_Data(uint8_t dat)
{
    hi_i2c_data i2c_buf = {0};
    uint8_t buf[2];
    buf[0] = 0x40;
    buf[1] = dat;
    i2c_buf.send_buf = buf;
    i2c_buf.send_len = 2;
    hi_i2c_write(0, OLED_ADDR, &i2c_buf);
}

// OLED初始化
void OLED_Init(void)
{
    hi_io_set_func(13, HI_IO_FUNC_GPIO_13_I2C0_SDA);
    hi_io_set_func(14, HI_IO_FUNC_GPIO_14_I2C0_SCL);
    hi_i2c_init(0, 400000);

    OLED_Write_Cmd(0xAE); // display off
    OLED_Write_Cmd(0xD5); // set clock
    OLED_Write_Cmd(0x80);
    OLED_Write_Cmd(0xA8); // multiplex ratio
    OLED_Write_Cmd(0x3F);
    OLED_Write_Cmd(0xD3); // display offset
    OLED_Write_Cmd(0x00);
    OLED_Write_Cmd(0x40); // start line
    OLED_Write_Cmd(0x8D); // charge pump
    OLED_Write_Cmd(0x14);
    OLED_Write_Cmd(0x20); // memory addr mode
    OLED_Write_Cmd(0x00);
    OLED_Write_Cmd(0xA1); // seg remap
    OLED_Write_Cmd(0xC8); // com scan
    OLED_Write_Cmd(0xDA); // com hardware
    OLED_Write_Cmd(0x12);
    OLED_Write_Cmd(0x81); // contrast
    OLED_Write_Cmd(0xCF);
    OLED_Write_Cmd(0xD9); // pre?charge
    OLED_Write_Cmd(0xF1);
    OLED_Write_Cmd(0xDB); // vcomh
    OLED_Write_Cmd(0x30);
    OLED_Write_Cmd(0xA4);
    OLED_Write_Cmd(0xA6);
    OLED_Write_Cmd(0xAF); // display ON
    OLED_Clear();
}

// 清屏
void OLED_Clear(void)
{
    uint16_t i;
    for(uint8_t page = 0; page < 8; page++)
    {
        OLED_Write_Cmd(0xB0 + page);
        OLED_Write_Cmd(0x00);
        OLED_Write_Cmd(0x10);
        for(i = 0; i < 128; i++){
            OLED_Write_Data(0x00);
        }
    }
}

// 在指定坐标显示单个字符
static void OLED_Show_Char(uint8_t x, uint8_t y, uint8_t ch)
{
    uint8_t c = 0, i = 0;
    if(x > 122) { x = 0; y++; }
    if(ch < ' ') ch = ' ';
    c = ch - ' ';
    OLED_Write_Cmd(0xB0 + y);
    OLED_Write_Cmd(((x & 0xF0)>>4)|0x10);
    OLED_Write_Cmd(x & 0x0F);
    for(i = 0; i < 6; i++)
    {
        OLED_Write_Data(F8X6[c*6 + i]);
    }
}

// 显示字符串
void OLED_ShowString(uint8_t x,uint8_t y,uint8_t *str)
{
    while(*str != '\0')
    {
        OLED_Show_Char(x,y,*str);
        x +=6;
        if(x>122){
            x=0;
            y++;
        }
        str++;
    }
}

